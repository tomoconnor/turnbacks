-- Change markers, inbound and outbound webhooks, and a persistent admin audit log.

-- New submission sources: generic JSON webhooks and chat integrations.
ALTER TABLE turnbacks DROP CONSTRAINT turnbacks_source_check;
ALTER TABLE turnbacks ADD CONSTRAINT turnbacks_source_check
    CHECK (source IN ('web', 'pwa_offline', 'api', 'cli', 'slack', 'webhook', 'mattermost', 'teams'));

-- A point in time when something changed ("VPN client 2.3 rolled out"), used
-- to compare equal windows before and after it. problem_id NULL means the
-- change applies to everything.
CREATE TABLE change_markers (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    occurred_at timestamptz NOT NULL,
    title       text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    description text NOT NULL DEFAULT '' CHECK (length(description) <= 2000),
    url         text CHECK (url IS NULL OR url ~* '^https?://'),
    problem_id  uuid REFERENCES problems (id) ON DELETE CASCADE,
    source      text NOT NULL CHECK (source IN ('web', 'api', 'cli', 'webhook')),
    created_by  text CHECK (created_by IS NULL OR length(created_by) <= 200),
    is_demo     boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX change_markers_occurred_at_idx ON change_markers (occurred_at);
CREATE INDEX change_markers_problem_idx ON change_markers (problem_id, occurred_at) WHERE problem_id IS NOT NULL;

-- Outbound webhooks: events are queued in webhook_deliveries and sent by a
-- background worker with retries.
CREATE TABLE webhooks (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name       text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
    url        text NOT NULL CHECK (url ~* '^https?://' AND length(url) <= 2000),
    format     text NOT NULL CHECK (format IN ('json', 'slack', 'markdown', 'teams')),
    events     text[] NOT NULL CHECK (cardinality(events) >= 1),
    -- HMAC key for the X-Turnbacks-Signature header (json format).
    secret     text NOT NULL,
    enabled    boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE webhook_deliveries (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    webhook_id       uuid NOT NULL REFERENCES webhooks (id) ON DELETE CASCADE,
    event            text NOT NULL,
    payload          jsonb NOT NULL,
    status           text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'delivered', 'failed')),
    attempts         integer NOT NULL DEFAULT 0,
    next_attempt_at  timestamptz NOT NULL DEFAULT now(),
    last_status_code integer,
    last_error       text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    delivered_at     timestamptz
);
CREATE INDEX webhook_deliveries_due_idx ON webhook_deliveries (next_attempt_at) WHERE status = 'pending';
CREATE INDEX webhook_deliveries_webhook_idx ON webhook_deliveries (webhook_id, created_at DESC);

-- Inbound webhooks: other systems record turnbacks or mark changes.
--   json        generic JSON with a bearer token generated by Turnbacks
--   mattermost  Mattermost slash command (token generated by Mattermost)
--   teams       Microsoft Teams outgoing webhook (HMAC key generated by Teams)
CREATE TABLE inbound_hooks (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name         text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
    kind         text NOT NULL CHECK (kind IN ('json', 'mattermost', 'teams')),
    -- SHA-256 of the bearer/slash-command token (json, mattermost).
    token_hash   bytea,
    -- Base64 HMAC key (teams); needed in clear to verify signatures.
    hmac_secret  text,
    enabled      boolean NOT NULL DEFAULT true,
    created_at   timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz,
    CHECK ((kind = 'teams') = (hmac_secret IS NOT NULL)),
    CHECK ((kind = 'teams') OR token_hash IS NOT NULL)
);

-- Administrative actions (and administrators' access to reporter data).
CREATE TABLE admin_audit (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    at         timestamptz NOT NULL DEFAULT now(),
    admin      text NOT NULL,
    via        text NOT NULL,
    method     text NOT NULL,
    action     text NOT NULL,
    target     text NOT NULL DEFAULT '',
    status     integer NOT NULL,
    client     text,
    request_id text
);
CREATE INDEX admin_audit_at_idx ON admin_audit (at DESC);

