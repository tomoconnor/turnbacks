// Inbound webhook kinds.
const (
	// InboundJSON accepts JSON requests authenticated with a bearer token
	// generated by Turnbacks (scripts, CI pipelines, monitoring).
	InboundJSON = "json"
	// InboundMattermost accepts Mattermost slash commands, authenticated with
	// the token Mattermost generates for the command.
	InboundMattermost = "mattermost"
	// InboundTeams accepts Microsoft Teams outgoing webhooks, authenticated
	// with an HMAC signature keyed with the security token Teams generates.
	InboundTeams = "teams"
)

// InboundKinds lists the inbound webhook kinds.
var InboundKinds = []string{InboundJSON, InboundMattermost, InboundTeams}

// InboundHookInput creates an inbound webhook. Secret is the credential
// generated by the other system (Mattermost token, Teams security token); it
// is ignored for json hooks, whose token Turnbacks generates.
type InboundHookInput struct {
	Name    string
	Kind    string
	Secret  string
	Enabled bool
}

// InboundHookCreated is a new inbound webhook plus the token to give the
// other system (json hooks only; shown once).
type InboundHookCreated struct {
	Hook  sqlc.InboundHook
	Token string
}

func tokenHash(t string) []byte {
	h := sha256.Sum256([]byte(t))
	return h[:]
}

// credential returns the stored form of the credential for kind.
func inboundCredential(kind, secret string) (hash []byte, hmacKey *string, token string, err error) {
	secret = strings.TrimSpace(secret)
	invalid := func(msg string) error {
		return &domain.Error{Kind: domain.KindInvalid, Code: "validation_failed", Message: "invalid secret",
			Fields: []domain.FieldError{{Field: "secret", Message: msg}}}
	}
	switch kind {
	case InboundJSON:
		token, err = newSecret("tbhook_")
		return tokenHash(token), nil, token, err
	case InboundMattermost:
		if len(secret) < 16 || len(secret) > 200 {
			return nil, nil, "", invalid("paste the token Mattermost generated for the slash command")
		}
		return tokenHash(secret), nil, "", nil
	case InboundTeams:
		if b, err := base64.StdEncoding.DecodeString(secret); err != nil || len(b) < 16 {
			return nil, nil, "", invalid("paste the security token Teams generated for the outgoing webhook")
		}
		return nil, &secret, "", nil
	}
	return nil, nil, "", invalid("unknown kind")
}

// ListInboundHooks lists inbound webhooks (administrators only).
func (s *Service) ListInboundHooks(ctx context.Context, a domain.Actor) ([]sqlc.InboundHook, error) {
	if err := requireAdmin(a); err != nil {
		return nil, err
	}
	return s.store.ListInboundHooks(ctx)
}

// CreateInboundHook adds an inbound webhook (administrators only).
func (s *Service) CreateInboundHook(ctx context.Context, a domain.Actor, in InboundHookInput) (InboundHookCreated, error) {
	if err := requireAdmin(a); err != nil {
		return InboundHookCreated{}, err
	}
	in.Name = strings.TrimSpace(in.Name)
	var v domain.Validator
	v.Check(len(in.Name) >= 1 && len(in.Name) <= 100, "name", "must be between 1 and 100 characters")
	v.Check(slices.Contains(InboundKinds, in.Kind), "kind", "must be json, mattermost or teams")
	if err := v.Err(); err != nil {
		return InboundHookCreated{}, err
	}
	hash, key, token, err := inboundCredential(in.Kind, in.Secret)
	if err != nil {
		return InboundHookCreated{}, err
	}
	h, err := s.store.CreateInboundHook(ctx, sqlc.CreateInboundHookParams{
		Name: in.Name, Kind: in.Kind, TokenHash: hash, HmacSecret: key, Enabled: in.Enabled,
	})
	return InboundHookCreated{Hook: h, Token: token}, err
}

// UpdateInboundHook renames or enables/disables an inbound webhook
// (administrators only).
func (s *Service) UpdateInboundHook(ctx context.Context, a domain.Actor, id uuid.UUID, name string, enabled bool) (sqlc.InboundHook, error) {
	if err := requireAdmin(a); err != nil {
		return sqlc.InboundHook{}, err
	}
	name = strings.TrimSpace(name)
	var v domain.Validator
	v.Check(len(name) >= 1 && len(name) <= 100, "name", "must be between 1 and 100 characters")
	if err := v.Err(); err != nil {
		return sqlc.InboundHook{}, err
	}
	h, err := s.store.UpdateInboundHook(ctx, sqlc.UpdateInboundHookParams{ID: id, Name: name, Enabled: enabled})
	return h, notFoundOr(err, "inbound webhook")
}

// ReplaceInboundCredential issues a new token (json) or stores a new secret
// from the other system (mattermost, teams). Administrators only.
func (s *Service) ReplaceInboundCredential(ctx context.Context, a domain.Actor, id uuid.UUID, secret string) (InboundHookCreated, error) {
	if err := requireAdmin(a); err != nil {
		return InboundHookCreated{}, err
	}
	h, err := s.store.GetInboundHook(ctx, id)
	if err != nil {
		return InboundHookCreated{}, notFoundOr(err, "inbound webhook")
	}
	hash, key, token, err := inboundCredential(h.Kind, secret)
	if err != nil {
		return InboundHookCreated{}, err
	}
	h, err = s.store.SetInboundHookCredential(ctx, sqlc.SetInboundHookCredentialParams{ID: id, TokenHash: hash, HmacSecret: key})
	return InboundHookCreated{Hook: h, Token: token}, err
}

// DeleteInboundHook removes an inbound webhook (administrators only).
func (s *Service) DeleteInboundHook(ctx context.Context, a domain.Actor, id uuid.UUID) error {
	if err := requireAdmin(a); err != nil {
		return err
	}
	n, err := s.store.DeleteInboundHook(ctx, id)
	if err == nil && n == 0 {
		return domain.NotFound("inbound webhook")
	}
	return err
}

// InboundHook returns an enabled inbound webhook for authentication by the
// inbound transport. Disabled and unknown hooks are both "not found".
func (s *Service) InboundHook(ctx context.Context, id uuid.UUID) (sqlc.InboundHook, error) {
	h, err := s.store.GetInboundHook(ctx, id)
	if err != nil && !store.IsNoRows(err) {
		return sqlc.InboundHook{}, err
	}
	if err != nil || !h.Enabled {
		return sqlc.InboundHook{}, domain.NotFound("inbound webhook")
	}
	return h, nil
}

// CheckInboundToken compares a presented token with the hook's stored hash
// in constant time.
func CheckInboundToken(h sqlc.InboundHook, token string) bool {
	return token != "" && h.TokenHash != nil && subtle.ConstantTimeCompare(tokenHash(token), h.TokenHash) == 1
}

// TouchInboundHook records that a hook was used.
func (s *Service) TouchInboundHook(ctx context.Context, id uuid.UUID) {
	if err := s.store.TouchInboundHook(ctx, id); err != nil {
		s.log.WarnContext(ctx, "inbound webhook: last use not saved", "error", err)
	}
}
